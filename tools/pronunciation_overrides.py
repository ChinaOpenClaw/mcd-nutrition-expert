def apply_overrides():
    """
    注入覆盖表到 pypinyin 词典。
    必须在 misaki 的 ZHG2P 实例化**之后**调用。
    """
    from pypinyin import load_phrases_dict
    clean = {k: v for k, v in ALL_OVERRIDES.items() if v}
    load_phrases_dict(clean)
    return len(clean)


def build_g2p():
    """构造带覆盖的 G2P 实例"""
    from misaki import zh
    g2p = zh.ZHG2P(version='1.1')
    apply_overrides()
    return g2p
